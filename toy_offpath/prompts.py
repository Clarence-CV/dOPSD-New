# A few short reasoning prompts for the toy experiment.
# These are intentionally simple so rollouts are short and the figure is clean.

PROMPTS = [
    "Natalia sold clips to 48 friends in April, and then she sold half as many clips in May. How many clips did she sell altogether in April and May?",
    "Weng earns $12 an hour for babysitting. Yesterday, she just did 50 minutes of babysitting. How much did she earn?",
    "Betty is saving money for a new wallet which costs $100. She has only half of the money she needs. Her parents give her $15, and her grandparents twice as much as her parents. How much more money does Betty need?",
    "James writes a 3-page letter to 2 different friends twice a week. How many pages does he write a year?",
    "A robe takes 2 bolts of blue fiber and half that much white fiber. How many bolts in total does it take?",
    "Tom has 12 apples. He gives 4 to his sister and buys 9 more. How many apples does Tom have now?",
    "A train travels 60 miles per hour for 3 hours. How far does it travel?",
    "If a book has 240 pages and Sara reads 30 pages per day, how many days will it take her to finish the book?",
    "There are 5 boxes, each containing 8 pencils. How many pencils are there in total?",
    "A rectangle has a length of 9 cm and a width of 4 cm. What is its area?",
    "Mary had 20 dollars. She spent 7 dollars on lunch and 5 dollars on a notebook. How much money does she have left?",
    "A baker makes 36 muffins and packs them equally into 4 boxes. How many muffins are in each box?",
    "John runs 5 kilometers every morning. How many kilometers does he run in one week?",
    "A class has 24 students. If they are split into groups of 6, how many groups are there?",
    "Lisa buys 3 packs of stickers. Each pack has 15 stickers. How many stickers does she have?",
    "A tank holds 200 liters of water. If 45 liters are used, how much water remains?",
]
